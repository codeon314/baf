using System;
using System.Collections.Concurrent;
using System.Net.WebSockets;
using System.Text;
using System.Text.Json;
using System.Threading;
using System.Threading.Tasks;
using BrowserAutomationFramework.Models;

using BrowserAutomationFramework.Extensions;

namespace BrowserAutomationFramework.Server
{
    /// <summary>
    /// Represents a connected browser tab instance (via the BAF Chrome Extension or Tampermonkey userscript)
    /// and manages bidirectional command execution and DOM/navigation event streaming.
    /// </summary>
    public class BrowserClient
    {
        /// <summary>
        /// Gets the unique identifier for this browser client session (e.g., <c>tab_123</c> or <c>bot_xyz</c>).
        /// </summary>
        public string InstanceId { get; }

        /// <summary>
        /// Gets the active IPC transport mode (<see cref="IpcMode.WebSocket"/> or <see cref="IpcMode.HttpPolling"/>) used by this client.
        /// </summary>
        public IpcMode Mode { get; private set; }

        /// <summary>
        /// Gets the UTC timestamp when the server last received a message or poll from this client.
        /// </summary>
        public DateTime LastSeen { get; internal set; } = DateTime.UtcNow;

        /// <summary>
        /// Gets the current URL loaded in the browser tab, if known.
        /// </summary>
        public string? CurrentUrl { get; internal set; }

        /// <summary>
        /// Gets the current document title of the browser tab, if known.
        /// </summary>
        public string? PageTitle { get; internal set; }

        /// <summary>
        /// Gets the unique correlation ID generated by the browser script for the current page load.
        /// </summary>
        public string? CurrentPageLoadId { get; private set; }

        /// <summary>
        /// Gets the most recent HTTP status code reported by the browser tab (e.g., 200 or 429).
        /// </summary>
        public int LastStatusCode { get; private set; } = 200;

        /// <summary>
        /// Gets the most recent <c>Retry-After</c> header value reported when <see cref="LastStatusCode"/> is 429.
        /// </summary>
        public string? LastRetryAfter { get; private set; }

        /// <summary>
        /// Gets the Chrome tab ID if this client was injected by the BAF Chrome Extension.
        /// </summary>
        public int? TabId { get; internal set; }

        /// <summary>
        /// Gets whether this client was injected by the BAF Chrome Extension rather than a Tampermonkey userscript.
        /// </summary>
        public bool IsExtensionClient => TabId.HasValue || InstanceId.StartsWith("tab_", StringComparison.OrdinalIgnoreCase);

        /// <summary>
        /// Gets a human-readable display string combining the client source (<c>[Ext]</c> or <c>[TM]</c>), <see cref="InstanceId"/>, and page title or host.
        /// </summary>
        public string DisplayName
        {
            get
            {
                string prefix = IsExtensionClient ? "[Ext]" : "[TM]";
                if (!string.IsNullOrWhiteSpace(PageTitle))
                {
                    string shortTitle = PageTitle.Length > 34 ? PageTitle.Substring(0, 31) + "..." : PageTitle;
                    return $"{prefix} {InstanceId} - {shortTitle}";
                }
                if (!string.IsNullOrWhiteSpace(CurrentUrl) && Uri.TryCreate(CurrentUrl, UriKind.Absolute, out var uri) && !string.IsNullOrWhiteSpace(uri.Host))
                {
                    return $"{prefix} {InstanceId} ({uri.Host})";
                }
                return $"{prefix} {InstanceId}";
            }
        }

        internal bool IsWebSocketConnected => _webSocket != null && _webSocket.State == WebSocketState.Open;

        private WebSocket? _webSocket;
        private readonly SemaphoreSlim _wsSendLock = new(1, 1);
        private TaskCompletionSource<bool> _wsReconnectTcs = new(TaskCreationOptions.RunContinuationsAsynchronously);
        private readonly ConcurrentQueue<CommandMessage> _httpCommandQueue = new();
        private readonly ConcurrentDictionary<string, (CommandMessage Command, TaskCompletionSource<CommandResult> Tcs)> _pendingCommands = new();
        private CancellationTokenSource? _highlightDebounceCts;
        private string? _lastHighlightedSelector;
        private int _domRefreshInFlight;
        private (string? TargetPath, bool HasTargetPath)? _pendingDomRefresh;
        private string? _lastUserSelectedDomPath;
        private DateTime _lastUserSelectionUtc = DateTime.MinValue;

        /// <summary>
        /// Gets the most recently fetched <see cref="DomTreeSnapshot"/> for this client, if any.
        /// </summary>
        public DomTreeSnapshot? CurrentDomSnapshot { get; internal set; }

        /// <summary>
        /// Gets the root <see cref="DomNode"/> of the most recently fetched DOM tree for this client, if any.
        /// </summary>
        public DomNode? CurrentDomRoot { get; internal set; }

        /// <summary>
        /// Resolves the most recent root <see cref="DomNode"/> for this client, falling back to <see cref="CurrentDomSnapshot"/> or <paramref name="fallbackDomRoot"/>.
        /// </summary>
        public DomNode? ResolveDomRoot(DomNode? fallbackDomRoot = null)
        {
            return CurrentDomRoot ?? CurrentDomSnapshot?.RootNode ?? fallbackDomRoot;
        }

        /// <summary>
        /// Gets the CSS selector of the most recently highlighted element on this client, if any.
        /// </summary>
        public string? LastHighlightedSelector => _lastHighlightedSelector;

        /// <summary>
        /// Resets the tracked highlight selector (or sets it to <paramref name="selector"/>) without sending a command to the browser.
        /// </summary>
        public void SetTrackedHighlightSelector(string? selector = null)
        {
            _lastHighlightedSelector = selector;
        }

        /// <summary>
        /// Records that the user explicitly selected a DOM path (via tree view click or browser middle-click)
        /// so in-flight DOM snapshot refreshes preserve the user's latest selection.
        /// </summary>
        public void RecordUserDomSelection(string? path, bool updateTrackedHighlight = false)
        {
            _lastUserSelectedDomPath = path;
            _lastUserSelectionUtc = DateTime.UtcNow;
            if (updateTrackedHighlight)
            {
                _lastHighlightedSelector = path;
            }
        }

        /// <summary>
        /// Records a user-initiated <see cref="DomNode"/> selection and optionally highlights the element in the connected browser tab with debouncing.
        /// </summary>
        public void SelectDomNode(DomNode? domNode, bool highlightInBrowser = true, int debounceMs = 25)
        {
            RecordUserDomSelection(domNode?.Path);
            if (highlightInBrowser && domNode != null && domNode.IsElement && domNode.HasPath)
            {
                HighlightElementDebounced(domNode.Path, debounceMs);
            }
        }

        /// <summary>
        /// Handles a browser middle-click element selection by attempting to select <paramref name="clickedPath"/> immediately via <paramref name="trySelectExistingPath"/>,
        /// or falling back to a coalesced DOM snapshot refresh targeting <paramref name="clickedPath"/> if the node is not yet present in the current tree.
        /// </summary>
        public async Task HandleElementClickedOrRefreshDomAsync(
            string? clickedPath,
            Func<string, bool> trySelectExistingPath,
            Action onSelectedInExistingTree,
            Func<string?> getCurrentSelectedPath,
            Action<DomSnapshotRefreshResult> onSnapshotReady,
            int timeoutSeconds = 10)
        {
            if (string.IsNullOrEmpty(clickedPath))
                return;

            if (trySelectExistingPath(clickedPath))
            {
                onSelectedInExistingTree();
                return;
            }

            await RefreshDomSnapshotCoalescedAsync(
                getCurrentSelectedPath,
                onSnapshotReady,
                targetSelectedPath: clickedPath,
                hasTargetPath: true,
                timeoutSeconds: timeoutSeconds).ConfigureAwait(true);
        }

        /// <summary>
        /// Executes a coalesced DOM tree snapshot refresh for this client. If a refresh is already in flight,
        /// queues the latest target request and invokes <paramref name="onSnapshotReady"/> for each completed snapshot.
        /// </summary>
        public async Task RefreshDomSnapshotCoalescedAsync(
            Func< string?> getCurrentSelectedPath,
            Action<DomSnapshotRefreshResult> onSnapshotReady,
            string? targetSelectedPath = null,
            bool hasTargetPath = false,
            int timeoutSeconds = 10)
        {
            if (Interlocked.CompareExchange(ref _domRefreshInFlight, 1, 0) != 0)
            {
                _pendingDomRefresh = (targetSelectedPath, hasTargetPath);
                return;
            }

            try
            {
                string? currentTarget = targetSelectedPath;
                bool currentHasTarget = hasTargetPath;

                while (true)
                {
                    _pendingDomRefresh = null;
                    DateTime fetchStartedUtc = DateTime.UtcNow;
                    string? previousSelectedPath = getCurrentSelectedPath();

                    using var fetchTimeoutCts = new CancellationTokenSource(TimeSpan.FromSeconds(timeoutSeconds));
                    DomTreeSnapshot? snapshot = null;
                    try
                    {
                        snapshot = await this.GetDomSnapshotAsync(fetchTimeoutCts.Token).ConfigureAwait(true);
                    }
                    catch (OperationCanceledException)
                    {
                        snapshot = null;
                    }

                    if (snapshot != null)
                    {
                        CurrentDomSnapshot = snapshot;
                        CurrentDomRoot = snapshot.RootNode;

                        bool userSelectedDuringFetch = _lastUserSelectionUtc > fetchStartedUtc &&
                                                       !string.IsNullOrEmpty(_lastUserSelectedDomPath);

                        string? finalSelectedPath;
                        if (userSelectedDuringFetch)
                        {
                            finalSelectedPath = _lastUserSelectedDomPath;
                        }
                        else if (currentHasTarget)
                        {
                            finalSelectedPath = !string.IsNullOrEmpty(currentTarget) ? currentTarget : previousSelectedPath;
                        }
                        else
                        {
                            finalSelectedPath = previousSelectedPath;
                        }

                        bool scrollSelectionIntoView = userSelectedDuringFetch ||
                            (currentHasTarget && !string.IsNullOrEmpty(currentTarget) &&
                             !string.Equals(currentTarget, previousSelectedPath, StringComparison.Ordinal));

                        onSnapshotReady(new DomSnapshotRefreshResult(snapshot, finalSelectedPath, scrollSelectionIntoView));
                    }

                    if (_pendingDomRefresh.HasValue)
                    {
                        var next = _pendingDomRefresh.Value;
                        _pendingDomRefresh = null;
                        currentTarget = next.TargetPath;
                        currentHasTarget = next.HasTargetPath;
                        await Task.Delay(150).ConfigureAwait(true);
                        continue;
                    }

                    break;
                }
            }
            finally
            {
                Interlocked.Exchange(ref _domRefreshInFlight, 0);
            }
        }

        /// <summary>
        /// Highlights the specified CSS selector in the browser using automatic debouncing and duplicate-selector suppression.
        /// Ideal for binding directly to UI tree view selection or hover events.
        /// </summary>
        public void HighlightElementDebounced(string? selector, int debounceMs = 25)
        {
            if (string.IsNullOrEmpty(selector))
                return;

            if (string.Equals(_lastHighlightedSelector, selector, StringComparison.Ordinal))
                return;

            _lastHighlightedSelector = selector;
            _highlightDebounceCts?.Cancel();
            var cts = new CancellationTokenSource();
            _highlightDebounceCts = cts;
            var token = cts.Token;

            _ = Task.Run(async () =>
            {
                try
                {
                    if (debounceMs > 0)
                    {
                        await Task.Delay(debounceMs, token).ConfigureAwait(false);
                    }
                    if (!token.IsCancellationRequested)
                    {
                        await this.HighlightElementAsync(selector, token).ConfigureAwait(false);
                    }
                }
                catch
                {
                    // Ignore transient or canceled highlight commands
                }
            }, token);
        }

        /// <summary>
        /// Triggered when the browser script streams partial data back for a long-running task.
        /// </summary>
        public event EventHandler<CommandResult>? OnStreamDataReceived;

        /// <summary>
        /// Triggered when the browser script sends an event.
        /// </summary>
        public event EventHandler<EventMessage>? OnEventReceived;

        /// <summary>
        /// Triggered when the page DOM mutates.
        /// </summary>
        public event EventHandler<DomChangedEventArgs>? OnDomChanged;

        /// <summary>
        /// Triggered when the currently highlighted element is removed from the page DOM.
        /// </summary>
        public event EventHandler? OnHighlightedElementRemoved;

        /// <summary>
        /// Triggered when an element is selected in the browser via middle-click.
        /// </summary>
        public event EventHandler<ElementClickedEventArgs>? OnElementClicked;

        /// <summary>
        /// Triggered when a page finishes loading (document.readyState === 'complete').
        /// </summary>
        public event EventHandler<PageLoadedEventArgs>? OnPageLoaded;

        /// <summary>
        /// Triggered when the client switches IPC transport modes (e.g., WebSocket to HttpPolling CSP fallback).
        /// </summary>
        public event EventHandler<IpcMode>? OnModeChanged;

        /// <summary>
        /// Initializes a new instance of the <see cref="BrowserClient"/> class.
        /// </summary>
        /// <param name="instanceId">The unique client instance identifier.</param>
        /// <param name="mode">The initial IPC transport mode.</param>
        /// <param name="webSocket">An optional active WebSocket connection when <paramref name="mode"/> is <see cref="IpcMode.WebSocket"/>.</param>
        public BrowserClient(string instanceId, IpcMode mode, WebSocket? webSocket = null)
        {
            InstanceId = instanceId;
            if (instanceId != null &&
                instanceId.StartsWith("tab_", StringComparison.OrdinalIgnoreCase) &&
                int.TryParse(instanceId.Substring(4), out int parsedTabId))
            {
                TabId = parsedTabId;
            }
            Mode = mode;
            _webSocket = webSocket;
            if (webSocket != null && webSocket.State == WebSocketState.Open)
            {
                _wsReconnectTcs.TrySetResult(true);
            }
        }

        internal async Task AttachWebSocketAsync(WebSocket webSocket, CancellationToken cancellationToken = default)
        {
            bool modeChanged = Mode != IpcMode.WebSocket;
            Mode = IpcMode.WebSocket;
            _webSocket = webSocket;
            LastSeen = DateTime.UtcNow;

            if (modeChanged)
            {
                OnModeChanged?.Invoke(this, Mode);
            }

            var oldTcs = Interlocked.Exchange(ref _wsReconnectTcs, new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously));
            oldTcs.TrySetResult(true);
            _wsReconnectTcs.TrySetResult(true);

            // Complete any navigation/click commands that triggered the page unload rather than re-sending them to the new page
            foreach (var entry in _pendingCommands.Values)
            {
                if (!entry.Tcs.Task.IsCompleted)
                {
                    string cmdType = entry.Command.Type ?? string.Empty;
                    if (string.Equals(cmdType, "REACT_CLICK", StringComparison.OrdinalIgnoreCase) ||
                        string.Equals(cmdType, "NAVIGATE", StringComparison.OrdinalIgnoreCase) ||
                        string.Equals(cmdType, "RELOAD_PAGE", StringComparison.OrdinalIgnoreCase))
                    {
                        entry.Tcs.TrySetResult(new CommandResult
                        {
                            TaskId = entry.Command.Id,
                            Status = "completed",
                            Output = "Link click executed (page navigated)"
                        });
                        continue;
                    }

                    try
                    {
                        await SendWebSocketMessageAsync(webSocket, entry.Command, cancellationToken);
                    }
                    catch
                    {
                        // Will be retried on next reconnect if socket dropped
                    }
                }
            }
        }

        internal void TouchHttpPolling()
        {
            LastSeen = DateTime.UtcNow;
            if (!IsWebSocketConnected)
            {
                bool modeChanged = Mode != IpcMode.HttpPolling;
                if (modeChanged)
                {
                    Mode = IpcMode.HttpPolling;
                    OnModeChanged?.Invoke(this, Mode);

                    var oldTcs = Interlocked.Exchange(ref _wsReconnectTcs, new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously));
                    oldTcs.TrySetResult(true);
                    _wsReconnectTcs.TrySetResult(true);

                    foreach (var entry in _pendingCommands.Values)
                    {
                        if (!entry.Tcs.Task.IsCompleted)
                        {
                            string cmdType = entry.Command.Type ?? string.Empty;
                            if (string.Equals(cmdType, "REACT_CLICK", StringComparison.OrdinalIgnoreCase) ||
                                string.Equals(cmdType, "NAVIGATE", StringComparison.OrdinalIgnoreCase) ||
                                string.Equals(cmdType, "RELOAD_PAGE", StringComparison.OrdinalIgnoreCase))
                            {
                                entry.Tcs.TrySetResult(new CommandResult
                                {
                                    TaskId = entry.Command.Id,
                                    Status = "completed",
                                    Output = "Link click executed (page navigated)"
                                });
                                continue;
                            }

                            EnqueueHttpCommandIfNotPresent(entry.Command);
                        }
                    }
                }
            }
        }

        private void EnqueueHttpCommandIfNotPresent(CommandMessage cmd)
        {
            foreach (var existing in _httpCommandQueue)
            {
                if (string.Equals(existing.Id, cmd.Id, StringComparison.Ordinal))
                    return;
            }
            _httpCommandQueue.Enqueue(cmd);
        }

        internal void DetachWebSocket(WebSocket webSocket)
        {
            LastSeen = DateTime.UtcNow;
            if (ReferenceEquals(_webSocket, webSocket))
            {
                _webSocket = null;
                Interlocked.Exchange(ref _wsReconnectTcs, new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously));
            }
        }

        internal void Disconnect()
        {
            _highlightDebounceCts?.Cancel();
            CurrentDomSnapshot = null;
            CurrentDomRoot = null;
            foreach (var kvp in _pendingCommands.ToArray())
            {
                if (_pendingCommands.TryRemove(kvp.Key, out var entry))
                {
                    entry.Tcs.TrySetCanceled();
                }
            }

            var reconnectTcs = Interlocked.Exchange(ref _wsReconnectTcs, new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously));
            reconnectTcs.TrySetCanceled();

            var ws = Interlocked.Exchange(ref _webSocket, null);
            if (ws != null)
            {
                try
                {
                    if (ws.State == WebSocketState.Open || ws.State == WebSocketState.CloseReceived)
                    {
                        ws.Abort();
                    }
                    ws.Dispose();
                }
                catch { }
            }
        }

        private async Task SendWebSocketMessageAsync(WebSocket socket, CommandMessage cmd, CancellationToken cancellationToken)
        {
            var json = JsonSerializer.Serialize(cmd);
            var bytes = Encoding.UTF8.GetBytes(json);
            await _wsSendLock.WaitAsync(cancellationToken);
            try
            {
                if (socket.State == WebSocketState.Open)
                {
                    await socket.SendAsync(new ArraySegment<byte>(bytes), WebSocketMessageType.Text, true, cancellationToken);
                }
            }
            finally
            {
                _wsSendLock.Release();
            }
        }

        private async Task<WebSocket?> WaitForActiveWebSocketOrFallbackAsync(int timeoutMs, CancellationToken cancellationToken)
        {
            var current = _webSocket;
            if (current != null && current.State == WebSocketState.Open)
                return current;

            if (Mode == IpcMode.HttpPolling)
                return null;

            using var timeoutCts = CancellationTokenSource.CreateLinkedTokenSource(cancellationToken);
            timeoutCts.CancelAfter(timeoutMs);

            await using (timeoutCts.Token.Register(() => _wsReconnectTcs.TrySetCanceled()))
            {
                try
                {
                    await _wsReconnectTcs.Task;
                }
                catch (OperationCanceledException) when (!cancellationToken.IsCancellationRequested)
                {
                    if (Mode == IpcMode.HttpPolling)
                        return null;

                    throw new TimeoutException("Timed out waiting for browser client WebSocket to reconnect after navigation.");
                }
            }

            current = _webSocket;
            if (current != null && current.State == WebSocketState.Open)
                return current;

            if (Mode == IpcMode.HttpPolling)
                return null;

            throw new InvalidOperationException("Client is disconnected.");
        }

        /// <summary>
        /// Sends a command to the browser and awaits the final result.
        /// Automatically handles transient WebSocket reconnections and CSP HTTP fallback during full-page navigations.
        /// </summary>
        public async Task<CommandResult> SendCommandAsync(string type, object? payload = null, CancellationToken cancellationToken = default)
        {
            var cmd = new CommandMessage { Type = type, Payload = payload };
            var tcs = new TaskCompletionSource<CommandResult>(TaskCreationOptions.RunContinuationsAsynchronously);
            _pendingCommands.TryAdd(cmd.Id, (cmd, tcs));

            try
            {
                if (Mode == IpcMode.WebSocket)
                {
                    var socket = await WaitForActiveWebSocketOrFallbackAsync(15000, cancellationToken);
                    if (socket != null)
                    {
                        try
                        {
                            await SendWebSocketMessageAsync(socket, cmd, cancellationToken);
                        }
                        catch when (!cancellationToken.IsCancellationRequested)
                        {
                            if (Mode == IpcMode.HttpPolling)
                            {
                                EnqueueHttpCommandIfNotPresent(cmd);
                            }
                        }
                    }
                    else
                    {
                        EnqueueHttpCommandIfNotPresent(cmd);
                    }
                }
                else if (Mode == IpcMode.HttpPolling)
                {
                    EnqueueHttpCommandIfNotPresent(cmd);
                }
                else
                {
                    throw new InvalidOperationException("Client is disconnected or invalid IPC mode.");
                }

                await using (cancellationToken.Register(() => tcs.TrySetCanceled()))
                {
                    return await tcs.Task;
                }
            }
            finally
            {
                _pendingCommands.TryRemove(cmd.Id, out _);
            }
        }

        /// <summary>
        /// Sends a command to the browser, automatically parsing JSON object/array strings if provided.
        /// </summary>
        public Task<CommandResult> SendRawCommandAsync(string type, string? rawPayload, CancellationToken cancellationToken = default)
        {
            object? payload = rawPayload;
            if (!string.IsNullOrWhiteSpace(rawPayload))
            {
                string trimmed = rawPayload.Trim();
                if (trimmed.StartsWith("{") || trimmed.StartsWith("["))
                {
                    try
                    {
                        payload = JsonSerializer.Deserialize<object>(trimmed, new JsonSerializerOptions { MaxDepth = 1024 }) ?? rawPayload;
                    }
                    catch
                    {
                        payload = rawPayload;
                    }
                }
            }

            return SendCommandAsync(type, payload, cancellationToken);
        }

        internal bool TryGetNextHttpCommand(out CommandMessage? command)
        {
            return _httpCommandQueue.TryDequeue(out command);
        }

        internal void HandleEvent(EventMessage evt)
        {
            OnEventReceived?.Invoke(this, evt);

            try
            {
                if (evt.Event == "DOM_CHANGED")
                {
                    string? highlightedPath = null;
                    bool hasHighlightedPath = false;
                    if (evt.Payload is JsonElement domPayload &&
                        domPayload.ValueKind == JsonValueKind.Object &&
                        domPayload.TryGetProperty("highlightedPath", out var hpProp))
                    {
                        hasHighlightedPath = true;
                        highlightedPath = hpProp.ValueKind == JsonValueKind.String ? hpProp.GetString() : null;
                    }

                    OnDomChanged?.Invoke(this, new DomChangedEventArgs(highlightedPath, hasHighlightedPath));
                }
                else if (evt.Event == "ELEMENT_REMOVED")
                {
                    OnHighlightedElementRemoved?.Invoke(this, EventArgs.Empty);
                }
                else if (evt.Event == "ELEMENT_CLICKED")
                {
                    if (evt.Payload is JsonElement clickPayload &&
                        clickPayload.ValueKind == JsonValueKind.Object &&
                        clickPayload.TryGetProperty("path", out var pathProp))
                    {
                        string? path = pathProp.GetString();
                        if (!string.IsNullOrEmpty(path))
                        {
                            RecordUserDomSelection(path, updateTrackedHighlight: true);
                            OnElementClicked?.Invoke(this, new ElementClickedEventArgs(path));
                        }
                    }
                }
                else if (evt.Event == "PAGE_LOADED")
                {
                    if (evt.Payload is JsonElement loadPayload &&
                        loadPayload.ValueKind == JsonValueKind.Object)
                    {
                        string pageLoadId = loadPayload.TryGetProperty("pageLoadId", out var idProp) ? (idProp.GetString() ?? string.Empty) : string.Empty;
                        string url = loadPayload.TryGetProperty("url", out var urlProp) ? (urlProp.GetString() ?? string.Empty) : string.Empty;
                        string readyState = loadPayload.TryGetProperty("readyState", out var rsProp) ? (rsProp.GetString() ?? "complete") : "complete";
                        int statusCode = loadPayload.TryGetProperty("statusCode", out var scProp) && scProp.TryGetInt32(out int parsedCode)
                            ? parsedCode
                            : 200;
                        string? retryAfter = loadPayload.TryGetProperty("retryAfter", out var raProp) && raProp.ValueKind == JsonValueKind.String
                            ? raProp.GetString()
                            : null;

                        bool isNewPageLoad = string.IsNullOrEmpty(pageLoadId) ||
                                             !string.Equals(CurrentPageLoadId, pageLoadId, StringComparison.Ordinal) ||
                                             (statusCode == 429 && LastStatusCode != 429);

                        string? title = loadPayload.TryGetProperty("title", out var titleProp) && titleProp.ValueKind == JsonValueKind.String
                            ? titleProp.GetString()
                            : null;

                        if (!string.IsNullOrEmpty(pageLoadId))
                            CurrentPageLoadId = pageLoadId;
                        if (!string.IsNullOrEmpty(url))
                            CurrentUrl = url;
                        if (!string.IsNullOrEmpty(title))
                            PageTitle = title;

                        LastStatusCode = statusCode;
                        LastRetryAfter = retryAfter;

                        if (isNewPageLoad)
                        {
                            OnPageLoaded?.Invoke(this, new PageLoadedEventArgs(pageLoadId, url, readyState, statusCode, retryAfter));
                        }
                    }
                }
            }
            catch
            {
                // Ignore malformed event payloads
            }
        }

        internal void HandleResult(CommandResult result)
        {
            if (result.Status == "streaming")
            {
                OnStreamDataReceived?.Invoke(this, result);
            }
            else
            {
                if (_pendingCommands.TryRemove(result.TaskId, out var pending))
                {
                    if (result.Status == "error")
                        pending.Tcs.TrySetException(new Exception(result.Output));
                    else
                        pending.Tcs.TrySetResult(result);
                }
            }
        }

        /// <summary>
        /// Returns <see cref="DisplayName"/>.
        /// </summary>
        public override string ToString() => DisplayName;
    }
